import { entryMinutes } from "../StaffRostering/rosterUtils";
import {
  breakMinutes,
  dayFlags,
  dayKeyOf,
  formatDayDate,
  formatDayName,
  formatDuration,
  formatTime,
  formatWeekLabel,
  getWeekDays,
  sumMinutes,
  summarizeDay,
} from "./attendanceUtils";

// The built-in PDF font only covers Latin characters, so the PDF uses English
// names / labels when there are any.
const pdfName = (staff) => staff?.fullName?.en || staff?.email || "-";
const PDF_LOCALE = "en-GB";
const FLAG_TEXT = {
  noClockIn: "! No clock-in",
  noClockOut: "! No clock-out",
  noLunchReturn: "! No lunch return",
  noLunchOut: "! No lunch clock-out",
};

function scheduledFor(staff, date) {
  return (staff?.scheduled || []).find((e) => e.date === dayKeyOf(date)) || null;
}

/** One day cell: worked hours, in/out, lunch, planned hours and any problems. */
function cellText(staff, date, now) {
  const day = summarizeDay(staff?.records, date, now);
  const planned = scheduledFor(staff, date);
  const plannedMin = entryMinutes(planned);
  const lines = [];
  if (day.status === "absent") lines.push("-");
  else {
    lines.push(formatDuration(day.minutes));
    const out = day.status === "checked-in" ? "now" : day.lastOut ? formatTime(day.lastOut, PDF_LOCALE) : "?";
    lines.push(`In ${formatTime(day.firstIn, PDF_LOCALE)} - Out ${out}`);
    day.sessions.forEach((s) =>
      (s.breaks || []).forEach((b) => {
        const mins = breakMinutes({ ...s, breaks: [b] }, now);
        lines.push(
          `Lunch ${formatTime(b.start, PDF_LOCALE)}-${b.end ? formatTime(b.end, PDF_LOCALE) : "?"} (${formatDuration(mins)})`,
        );
      }),
    );
  }
  if (plannedMin) lines.push(`Planned ${formatDuration(plannedMin)}`);
  dayFlags(day, planned, date, now).forEach((f) => lines.push(FLAG_TEXT[f]));
  if (day.sessions.some((s) => s.manual || s.corrections?.length)) lines.push("* Corrected");
  return lines.join("\n");
}

const fmt = (d) => (d ? new Date(d).toLocaleString(PDF_LOCALE, { dateStyle: "short", timeStyle: "short" }) : "-");
const snapText = (snap) => {
  if (!snap) return "No record";
  const lunch = (snap.breaks || [])
    .map((b) => `${formatTime(b.start, PDF_LOCALE)}-${b.end ? formatTime(b.end, PDF_LOCALE) : "?"}`)
    .join(", ");
  return `In ${fmt(snap.checkIn)}\nOut ${snap.checkOut ? fmt(snap.checkOut) : "-"}${lunch ? `\nLunch ${lunch}` : ""}`;
};

/** Builds and downloads the weekly attendance report as a PDF. */
export async function downloadAttendancePdf({ rows, weekStart, centreName, generatedBy }) {
  // Loaded on demand so the PDF library isn't part of the page bundle
  const [{ jsPDF }, { default: autoTable }] = await Promise.all([
    import("jspdf"),
    import("jspdf-autotable"),
  ]);

  const now = new Date();
  const days = getWeekDays(weekStart);
  const doc = new jsPDF({ orientation: "landscape", unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();

  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(23, 42, 51);
  doc.text("Weekly Staff Attendance", 40, 46);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10.5);
  doc.setTextColor(90, 100, 110);
  doc.text(`Centre: ${centreName || "-"}`, 40, 64);
  doc.text(`Week: ${formatWeekLabel(weekStart, PDF_LOCALE)}`, 40, 79);
  doc.text(`Generated by: ${generatedBy || "-"}`, pageWidth - 40, 64, { align: "right" });
  doc.text(
    `Generated: ${now.toLocaleString(PDF_LOCALE, { dateStyle: "medium", timeStyle: "short" })}`,
    pageWidth - 40,
    79,
    { align: "right" },
  );

  const head = [
    [
      "Name",
      ...days.map((d) => `${formatDayName(d, PDF_LOCALE)}\n${formatDayDate(d, PDF_LOCALE)}`),
      "Lunch (week)",
      "Actual / Planned",
    ],
  ];

  const body = rows.map((staff) => {
    const actual = sumMinutes(staff?.records || [], now);
    const lunch = (staff?.records || []).reduce((n, r) => n + breakMinutes(r, now), 0);
    const planned = days.reduce((sum, d) => sum + entryMinutes(scheduledFor(staff, d)), 0);
    const diff = actual - planned;
    return [
      pdfName(staff),
      ...days.map((d) => cellText(staff, d, now)),
      lunch ? formatDuration(lunch) : "-",
      `${formatDuration(actual)}\n/ ${planned ? formatDuration(planned) : "-"}${
        planned ? `\n(${diff >= 0 ? "+" : "-"}${formatDuration(Math.abs(diff))})` : ""
      }`,
    ];
  });

  autoTable(doc, {
    head,
    body,
    startY: 92,
    margin: { left: 30, right: 30 },
    styles: {
      font: "helvetica",
      fontSize: 7.5,
      cellPadding: 4,
      valign: "middle",
      textColor: [23, 42, 51],
      lineColor: [230, 234, 240],
      lineWidth: 0.5,
    },
    headStyles: { fillColor: [51, 181, 246], textColor: [255, 255, 255], fontStyle: "bold", halign: "center" },
    columnStyles: {
      0: { cellWidth: 95, fontStyle: "bold" },
      8: { halign: "center", cellWidth: 52 },
      9: { fontStyle: "bold", halign: "center", cellWidth: 70 },
    },
    bodyStyles: { halign: "center" },
    alternateRowStyles: { fillColor: [244, 247, 253] },
    didParseCell: (hook) => {
      if (hook.section !== "body") return;
      if (hook.column.index === 0) hook.cell.styles.halign = "left";
      const raw = String(hook.cell.raw || "");
      if (raw.includes("! ")) hook.cell.styles.textColor = [180, 35, 24];
    },
  });

  if (!rows.length) {
    doc.setFontSize(11);
    doc.setTextColor(140, 147, 155);
    doc.text("No staff found for this week.", 40, 130);
  }

  // Approved corrections (audit trail). Corrections can only be made by an
  // authorised manager — staff cannot change their own times — so each one is
  // an approved correction, with the approving manager and reason.
  const corrections = rows.flatMap((staff) =>
    (staff.records || []).flatMap((rec) =>
      (rec.corrections || []).map((c) => [
        pdfName(staff),
        new Date(rec.checkIn).toLocaleDateString(PDF_LOCALE, { weekday: "short", day: "numeric", month: "short" }),
        snapText(c.before),
        snapText(c.after),
        c.correctedBy?.fullName?.en || "-",
        fmt(c.correctedAt),
        c.reason || "-",
      ]),
    ),
  );

  let y = (doc.lastAutoTable?.finalY || 100) + 26;
  if (y > doc.internal.pageSize.getHeight() - 80) {
    doc.addPage();
    y = 46;
  }
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.setTextColor(23, 42, 51);
  doc.text("Approved attendance corrections", 40, y);
  if (!corrections.length) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.setTextColor(140, 147, 155);
    doc.text("No approved corrections this week.", 40, y + 18);
  } else {
    autoTable(doc, {
      head: [["Staff", "Day", "Original", "Corrected", "Approved by (manager)", "When", "Reason"]],
      body: corrections,
      startY: y + 10,
      margin: { left: 30, right: 30 },
      styles: { font: "helvetica", fontSize: 8, cellPadding: 4, textColor: [23, 42, 51], lineColor: [230, 234, 240], lineWidth: 0.5 },
      headStyles: { fillColor: [23, 42, 51], textColor: [255, 255, 255], fontStyle: "bold" },
      columnStyles: { 6: { cellWidth: 170 } },
    });
  }

  doc.save(`staff-attendance-${dayKeyOf(weekStart)}.pdf`);
}
